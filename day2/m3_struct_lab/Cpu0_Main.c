#include "Ifx_Types.h"
#include "IfxCpu.h"
#include "IfxScuWdt.h"
#include <stdio.h>

IfxCpu_syncEvent g_cpuSyncEvent = 0;


void core0_main(void)
{

    IfxCpu_enableInterrupts();
    
    /* !!WATCHDOG0 AND SAFETY WATCHDOG ARE DISABLED HERE!!
     * Enable the watchdogs and service them periodically if it is required
     */
    IfxScuWdt_disableCpuWatchdog(IfxScuWdt_getCpuWatchdogPassword());
    IfxScuWdt_disableSafetyWatchdog(IfxScuWdt_getSafetyWatchdogPassword());
    
    /* Wait for CPU sync event */
    IfxCpu_emitEvent(&g_cpuSyncEvent);
    IfxCpu_waitEvent(&g_cpuSyncEvent, 1);

    typedef struct {
            unsigned char        ST: 1; // 1bit 크기만 할당.
            unsigned char _reserved: 6; // 공간확보
            unsigned char        EN: 1; // 1bit만 할당.
    } bit8;

    typedef struct {
           unsigned short CNT;
           unsigned char  SPEED;
         //unsigned char  MODE;
           bit8           MODE;
   } TMR_R;

    #define TMR1 (*((TMR_R*)0x700195F0))
    TMR1.CNT   = 0x5678;
    TMR1.SPEED = 0x34;
    //TMR1.MODE  = 0x81;
    TMR1.MODE.EN = 1;
    TMR1.MODE.ST = 1;

    TMR1.CNT = 0x0000;
    TMR1.SPEED = 0x00;
    TMR1.MODE.EN  = 0;
    TMR1.MODE.ST  = 0;

    typedef union {
            TMR_R        t;
            unsigned int m;
    } TMR_HAL;

#define TMR_H1 (*((TMR_HAL*)0x700195F0))

    TMR_H1.m = 0x7EBBCCDD;
    TMR_H1.t.CNT = 0x55FC;
    TMR_H1.t.SPEED = 0x66;
    TMR_H1.t.MODE.EN = 1;
    TMR_H1.t.MODE.ST = 1;

    TMR_H1.m = 0x00000000;


    while(1)
    {
    }
}
