#include "Ifx_Types.h"
#include "IfxCpu.h"
#include "IfxScuWdt.h"
#include <stdio.h>

IfxCpu_syncEvent g_cpuSyncEvent = 0;

int core0_main(void)
{
    IfxCpu_enableInterrupts();
    
    /* !!WATCHDOG0 AND SAFETY WATCHDOG ARE DISABLED HERE!!
     * Enable the watchdogs and service them periodically if it is required
     */
    IfxScuWdt_disableCpuWatchdog(IfxScuWdt_getCpuWatchdogPassword());
    IfxScuWdt_disableSafetyWatchdog(IfxScuWdt_getSafetyWatchdogPassword());
    
    /* Wait for CPU sync event */
    IfxCpu_emitEvent(&g_cpuSyncEvent);
    IfxCpu_waitEvent(&g_cpuSyncEvent, 1);
    

    // 이제 주어진 메모리 공간을
        //  1. 서로다른 크기의 방으로 나누어서 사용하고
        //  2. 각방에 적절한 이름까지 부여해볼수 없을까?
        //
        // 이를 위해 주어진 공간(방)의 설계도를 만드는 방법이 바로 구조체임
        //  사용자가 방의 구조를 정의할 수 있는 user-defined data type
        //
        // 31            16 15        8 7          0
        // +--------------+------------+-----------+
        // |    MODE      |    CNFG2   |   CNFG1   |
        // +--------------+------------+-----------+
        //  Little Endian일때, 하위 LSB 바이트 부터 먼저 선언해야 함.

    typedef struct {
        unsigned char CNFG0;
        unsigned char CNFG1;
        unsigned short MODE;
    } ADC_CONFIG;

    ADC_CONFIG adc1;

    adc1.CNFG0 = 0x7F;
    adc1.CNFG1 = 0x88;
    adc1.MODE = 0x5ACD;

    printf("adc CNF0: 0x%02X\n", adc1.CNFG0);
    printf("adc CNF1: 0x%02X\n", adc1.CNFG1);
    printf("adc MODE: 0x%04X\n", adc1.MODE);


    // 같은 메모리 영역을 이제 int가 아닌 구조체로 바라보자!!
    #define ADC_CNFG_IF (*(volatile ADC_CONFIG*)0x700195F0)
    ADC_CNFG_IF.CNFG0 = 0x5A;
    ADC_CNFG_IF.CNFG1 = 0xBB;
    ADC_CNFG_IF.MODE  = 0x6712;


    // bit slice 표현방법
    typedef struct {
        unsigned char b0: 1;
        unsigned char b1: 1;
        unsigned char b2: 1;
        unsigned char b3: 1;
        unsigned char b4: 1;
        unsigned char b5: 1;
        unsigned char b6: 1;
        unsigned char b7: 1;
    } bits;

    // 어떤 메모리 영역을 여러 타입드로 바라볼수있게 해주는것 union
    typedef union {
        unsigned int  u;
        ADC_CONFIG    c;
        unsigned char a[4];
        bits          b[4];
    } ADC_CONFIG_U;

    ADC_CONFIG_U a1;
    a1.u = 0x55BBCCDD;
    a1.a[2] = 0xFF;
    a1.c.CNFG0 = 0x43;
    a1.b[1].b2 = 1; // 특정 비트 조작.

    printf("a1: 0x%08X\n", a1.u);


    while(1)
    {
    }
    return (1);
}
